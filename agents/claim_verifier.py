"""Deterministic claim verification engine for SignalGate Gate G3.

Enforces that LLM agents cannot display unverified statements or arbitrary prose.
All statements presented to fraud analysts must be generated by a registered template
populated exclusively by verified facts cross-checked against the permitted AgentCaseView.

Key Invariants:
1. Extra or malformed claim fields are rejected.
2. Only explicitly registered (field, operator) pairs are permitted.
3. Values are verified strictly against the permitted AgentCaseView.
4. Only registered template_id values are permitted.
5. Final prose is rendered strictly from reviewed templates after verification.
6. The verifier is completely deterministic.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Mapping

from schemas.agent_view import AgentCaseView
from schemas.contracts import Claim


# Registered template definitions for verified claim presentation
REGISTERED_TEMPLATES: dict[str, str] = {
    "T1_CALIBRATED_RISK": "Case {record_id} evaluated with calibrated fraud risk p={p:.4f}.",
    "T2_MODEL_DISAGREEMENT": "Ensemble disagreement across members is u={u:.4f}.",
    "T3_ROUTING_ACTION": "Deterministic triage assigned action '{action}' with reason code '{reason}'.",
    "T4_HIGH_RISK_THRESHOLD": "Calibrated risk p={p:.4f} is at or above review threshold {threshold:.4f}.",
    "T5_MODERATE_RISK_RANGE": "Calibrated risk p={p:.4f} falls within intermediate review band [{lower:.4f}, {upper:.4f}].",
    "T6_ELEVATED_DISAGREEMENT": "Disagreement signal u={u:.4f} is elevated above baseline spread {threshold:.4f}.",
    "T7_ROBUST_MAD_SIGNAL": "Robust disagreement MAD from median is u2={u2:.4f}.",
    "T8_RECORD_PROVENANCE": "Audit provenance verified against config hash {cfg_hash_short} and split hash {split_hash_short}.",
    "T9_MEMBER_COUNT": "Ensemble evaluated with n={n:.0f} active scoring members.",
}

# Explicitly allowed (field, operator) combinations
ALLOWED_FIELD_OPERATORS: set[tuple[str, str]] = {
    ("p", "eq"),
    ("p", "lt"),
    ("p", "lte"),
    ("p", "gt"),
    ("p", "gte"),
    ("u", "eq"),
    ("u", "lt"),
    ("u", "lte"),
    ("u", "gt"),
    ("u", "gte"),
    ("u2", "eq"),
    ("u2", "lt"),
    ("u2", "lte"),
    ("u2", "gt"),
    ("u2", "gte"),
    ("n", "eq"),
    ("n", "gte"),
    ("action", "eq"),
    ("action", "in"),
    ("reason", "eq"),
    ("reason", "in"),
    ("record_id", "eq"),
    ("cfg_hash", "eq"),
    ("split_hash", "eq"),
    ("record_hash", "eq"),
}


@dataclass(frozen=True)
class VerificationResult:
    """Outcome of verifying a single structured claim against an AgentCaseView."""

    is_verified: bool
    statement: str | None
    rejection_reason: str | None


class ClaimVerifier:
    """Deterministic, schema-enforcing claim verifier."""

    def __init__(
        self,
        templates: Mapping[str, str] | None = None,
        allowed_field_operators: set[tuple[str, str]] | None = None,
    ) -> None:
        self.templates = dict(templates if templates is not None else REGISTERED_TEMPLATES)
        self.allowed_field_operators = set(
            allowed_field_operators if allowed_field_operators is not None else ALLOWED_FIELD_OPERATORS
        )

    def verify(self, claim: Claim, case_view: AgentCaseView) -> VerificationResult:
        """Verify a claim deterministically against an AgentCaseView.

        Rejects malformed claims, unsupported fields, unknown operators,
        unregistered templates, and factual inaccuracies.
        """
        # 1. Type validation
        if not isinstance(claim, Claim):
            return VerificationResult(
                is_verified=False,
                statement=None,
                rejection_reason=f"Expected Claim instance, got {type(claim).__name__}",
            )

        if not isinstance(case_view, AgentCaseView):
            return VerificationResult(
                is_verified=False,
                statement=None,
                rejection_reason=f"Expected AgentCaseView instance, got {type(case_view).__name__}",
            )

        # 2. Template registration check
        template_id = claim.template_id
        if template_id not in self.templates:
            return VerificationResult(
                is_verified=False,
                statement=None,
                rejection_reason=f"Unregistered template_id: '{template_id}'",
            )

        # 3. Field / Operator registration check
        field_name = claim.field
        operator = claim.operator
        if (field_name, operator) not in self.allowed_field_operators:
            return VerificationResult(
                is_verified=False,
                statement=None,
                rejection_reason=f"Unsupported field/operator combination: ({field_name}, {operator})",
            )

        # 4. Field existence on AgentCaseView
        if not hasattr(case_view, field_name):
            return VerificationResult(
                is_verified=False,
                statement=None,
                rejection_reason=f"Field '{field_name}' does not exist on AgentCaseView",
            )

        actual_val = getattr(case_view, field_name)
        if actual_val is None:
            return VerificationResult(
                is_verified=False,
                statement=None,
                rejection_reason=f"Case field '{field_name}' is None and cannot be evaluated",
            )

        # 5. Numerical / Logical value verification
        is_factually_true = self._evaluate_condition(actual_val, operator, claim.value)
        if not is_factually_true:
            return VerificationResult(
                is_verified=False,
                statement=None,
                rejection_reason=(
                    f"Factual verification failed for field '{field_name}': "
                    f"actual={actual_val!r} does not satisfy {operator} {claim.value!r}"
                ),
            )

        # 6. Render user-facing statement from pre-reviewed template
        try:
            rendered = self._render_template(template_id, claim, case_view)
        except Exception as exc:
            return VerificationResult(
                is_verified=False,
                statement=None,
                rejection_reason=f"Template rendering error for {template_id}: {exc}",
            )

        return VerificationResult(
            is_verified=True,
            statement=rendered,
            rejection_reason=None,
        )

    def verify_all(
        self,
        claims: list[Claim],
        case_view: AgentCaseView,
    ) -> tuple[list[Claim], list[str], list[str]]:
        """Verify multiple claims, partitioning into verified claims, statements, and rejections."""
        verified_claims: list[Claim] = []
        verified_statements: list[str] = []
        rejection_reasons: list[str] = []

        for c in claims:
            res = self.verify(c, case_view)
            if res.is_verified and res.statement is not None:
                verified_claims.append(c)
                verified_statements.append(res.statement)
            else:
                rejection_reasons.append(res.rejection_reason or "Unknown verification error")

        return verified_claims, verified_statements, rejection_reasons

    @staticmethod
    def _evaluate_condition(actual: Any, operator: str, expected: Any) -> bool:
        """Evaluate mathematical and relational operator deterministically."""
        # Floating point tolerance
        if isinstance(actual, (int, float)) and isinstance(expected, (int, float)):
            actual_f = float(actual)
            expected_f = float(expected)
            tol = 1e-4

            if operator == "eq":
                return abs(actual_f - expected_f) <= tol
            elif operator == "ne":
                return abs(actual_f - expected_f) > tol
            elif operator == "lt":
                return actual_f < (expected_f - tol)
            elif operator == "lte":
                return actual_f <= (expected_f + tol)
            elif operator == "gt":
                return actual_f > (expected_f + tol)
            elif operator == "gte":
                return actual_f >= (expected_f - tol)
            elif operator == "in":
                return False

        # Categorical / string comparison
        if operator == "eq":
            return actual == expected
        elif operator == "ne":
            return actual != expected
        elif operator == "in":
            try:
                return actual in expected
            except TypeError:
                return False
        elif operator in ("lt", "lte", "gt", "gte"):
            try:
                if operator == "lt":
                    return actual < expected
                elif operator == "lte":
                    return actual <= expected
                elif operator == "gt":
                    return actual > expected
                elif operator == "gte":
                    return actual >= expected
            except TypeError:
                return False

        return False

    def _render_template(
        self,
        template_id: str,
        claim: Claim,
        case_view: AgentCaseView,
    ) -> str:
        """Render approved statement with strict parameter formatting."""
        template = self.templates[template_id]
        context: dict[str, Any] = {
            "record_id": case_view.record_id,
            "action": case_view.action,
            "reason": case_view.reason,
            "p": case_view.p if case_view.p is not None else 0.0,
            "u": case_view.u if case_view.u is not None else 0.0,
            "u2": case_view.u2 if case_view.u2 is not None else 0.0,
            "n": case_view.n if case_view.n is not None else 0.0,
            "cfg_hash": case_view.cfg_hash,
            "cfg_hash_short": case_view.cfg_hash[:8],
            "split_hash": case_view.split_hash,
            "split_hash_short": case_view.split_hash[:8],
            "threshold": float(claim.value) if isinstance(claim.value, (int, float)) else 0.0,
            "lower": float(claim.value[0]) if isinstance(claim.value, (list, tuple)) and len(claim.value) > 0 else 0.0,
            "upper": float(claim.value[1]) if isinstance(claim.value, (list, tuple)) and len(claim.value) > 1 else 1.0,
        }
        return template.format(**context)
